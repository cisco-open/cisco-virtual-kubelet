package transport

import (
	"context"
	"crypto/subtle"
	"encoding/base64"
	"fmt"
	"net"
	"regexp"
	"strconv"
	"strings"
	"time"

	"golang.org/x/crypto/ssh"
)

// AppPackageChecksumConfig uses the device's existing SSH CLI solely for
// staged-file metadata and native SHA512. It never transfers a file or installs
// an application. A missing/mismatched host-key pin always fails closed.
type AppPackageChecksumConfig struct {
	Address, Username, Password, HostKeySHA256 string
}

var ownedAppPackagePath = regexp.MustCompile(`^flash:cvk-[a-f0-9]{16}-[a-f0-9]{64}\.tar$`)
var fileSHA512 = regexp.MustCompile(`^[a-f0-9]{128}$`)

// VerifyAppPackageFile verifies exactly the staged app archive, not an embedded
// Cisco platform-image signature. The expected SHA512 must be derived from bytes
// already validated against the signed descriptor's SHA256 and exact size.
func VerifyAppPackageFile(ctx context.Context, cfg AppPackageChecksumConfig, path string, size int64, expectedSHA512 string) error {
	if !ownedAppPackagePath.MatchString(path) || size < 1 || !fileSHA512.MatchString(expectedSHA512) {
		return fmt.Errorf("invalid owned application file checksum request")
	}
	pin, err := base64.RawStdEncoding.DecodeString(strings.TrimPrefix(cfg.HostKeySHA256, "SHA256:"))
	if !strings.HasPrefix(cfg.HostKeySHA256, "SHA256:") || err != nil || len(pin) != 32 {
		return fmt.Errorf("application checksum requires a pinned SSH SHA256 host key")
	}
	if cfg.Address == "" || cfg.Username == "" || cfg.Password == "" {
		return fmt.Errorf("application checksum requires the device address and credentials")
	}
	commands := []string{"dir " + path, "verify /sha512 " + path}
	results, err := runCommandsViaSSHContext(ctx, sshCLIConfig{Address: cfg.Address, Username: cfg.Username, Password: cfg.Password, Timeout: 2 * time.Minute, HostKeyCallback: func(_ string, _ net.Addr, key ssh.PublicKey) error {
		if subtle.ConstantTimeCompare([]byte(ssh.FingerprintSHA256(key)), []byte(cfg.HostKeySHA256)) != 1 {
			return fmt.Errorf("application checksum SSH host key mismatch")
		}
		return nil
	}}, commands)
	if err != nil {
		return fmt.Errorf("application checksum query: %w", err)
	}
	if len(results) != 2 {
		return fmt.Errorf("incomplete application checksum response")
	}
	for _, r := range results {
		if r.Err != "" {
			return fmt.Errorf("native application checksum command rejected")
		}
	}
	return validateAppPackageChecksumOutput(path, size, expectedSHA512, results[0].Output, results[1].Output)
}

func validateAppPackageChecksumOutput(path string, size int64, expectedSHA512, listing, verification string) error {
	// Require one exact, writable regular-file entry with the expected basename.
	// The path itself is generated by CVK and excludes CLI delimiters/whitespace.
	basename := strings.TrimPrefix(path, "flash:")
	entry := regexp.MustCompile(`(?m)^\s*[0-9]+\s+-rw-\s+([0-9]+)\s+[^\r\n]*\s` + regexp.QuoteMeta(basename) + `\s*$`)
	matches := entry.FindAllStringSubmatch(listing, -1)
	if len(matches) != 1 {
		return fmt.Errorf("exact staged application file metadata unavailable")
	}
	n, err := strconv.ParseInt(matches[0][1], 10, 64)
	if err != nil || n != size {
		return fmt.Errorf("on-device application package size mismatch")
	}
	hashLine := regexp.MustCompile(`(?m)^verify /sha512 \(` + regexp.QuoteMeta(path) + `\) = ([a-fA-F0-9]{128})\s*$`)
	hashes := hashLine.FindAllStringSubmatch(verification, -1)
	if len(hashes) != 1 || !strings.EqualFold(hashes[0][1], expectedSHA512) {
		return fmt.Errorf("on-device application package SHA512 mismatch or unsupported verification response")
	}
	return nil
}
