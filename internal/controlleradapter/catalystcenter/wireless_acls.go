const wirelessACLsPath = "/dna/intent/api/v1/wirelessSettings/preAuthAcls"

type wirelessACLRule struct {
	Source            string `json:"sourceAddress"`
	SourcePrefix      int    `json:"sourceSubnetMaskOrPrefix"`
	Destination       string `json:"destinationAddress"`
	DestinationPrefix int    `json:"destinationSubnetMaskOrPrefix"`
	SourcePorts       string `json:"sourcePorts"`
	DestinationPorts  string `json:"destinationPorts"`
	Protocol          string `json:"protocol"`
}
type wirelessACL struct {
	ID        string            `json:"id,omitempty"`
	Name      string            `json:"aclListName"`
	ACLName   string            `json:"aclName"`
	IPv6      bool              `json:"ipv6AclEnabled"`
	AutoRules bool              `json:"includeAutoGeneratedRules"`
	Rules     []wirelessACLRule `json:"ipAclRules"`
	URLs      []string          `json:"walledGardenUrls,omitempty"`
}

var aclGardenPattern = regexp.MustCompile(`^[A-Za-z0-9_.*-]+$`)
var aclPortsPattern = regexp.MustCompile(`^[0-9]+(-[0-9]+)?$`)

func validACLPorts(s string) bool {
	if !aclPortsPattern.MatchString(s) {
		return false
	}
	parts := strings.Split(s, "-")
	low, err := strconv.Atoi(parts[0])
	if err != nil || low > 65535 {
		return false
	}
	if len(parts) == 2 {
		high, err := strconv.Atoi(parts[1])
		return err == nil && high >= low && high <= 65535
	}
	return true
}
func validateWirelessACL(a *wirelessACL) error {
	if !validProfileName(a.Name) || !validProfileName(a.ACLName) {
		return errInvalidResponse
	}
	protocols := []string{"ANY", "AHP", "ESP", "GRE", "ICMP", "IGMP", "IP", "IPINIP", "NOS", "OSPF", "PCP", "PIM", "TCP", "UDP"}
	maxPrefix := 32
	if a.IPv6 {
		maxPrefix = 128
		protocols = []string{"ANY", "AHP", "ESP", "ICMPV6", "IPV6", "PCP", "SCTP", "TCP", "UDP"}
	}
	if len(a.Rules) > 1000 || len(a.URLs) > 1000 {
		return errInvalidResponse
	}
	for i := range a.Rules {
		r := &a.Rules[i]
		src, e1 := netip.ParseAddr(r.Source)
		dst, e2 := netip.ParseAddr(r.Destination)
		if e1 != nil || e2 != nil || src.Zone() != "" || dst.Zone() != "" || src.Is4In6() || dst.Is4In6() || src.Is6() != a.IPv6 || dst.Is6() != a.IPv6 || r.SourcePrefix < 0 || r.SourcePrefix > maxPrefix || r.DestinationPrefix < 0 || r.DestinationPrefix > maxPrefix || !slices.Contains(protocols, r.Protocol) || !validACLPorts(r.SourcePorts) || !validACLPorts(r.DestinationPorts) {
			return errInvalidResponse
		}
		r.Source = src.String()
		r.Destination = dst.String()
	}
	sort.Strings(a.URLs)
	for i, v := range a.URLs {
		if len(v) > 253 || !aclGardenPattern.MatchString(v) || (i > 0 && v == a.URLs[i-1]) {
			return errInvalidResponse
		}
	}
	return nil
}
func parseWirelessACLs(raw []byte) ([]wirelessACL, error) {
	node, err := nacmodel.ParseDocument(raw)
	if err != nil {
		return nil, err
	}
	var root map[string]any
	if node.Decode(&root) != nil || len(root) != 1 {
		return nil, errors.New("wireless requires a section-specific model")
	}
	wireless, ok := root["wireless"].(map[string]any)
	if !ok || len(wireless) != 1 {
		return nil, errors.New("unsupported wireless collection")
	}
	security, ok := wireless["security_settings"].(map[string]any)
	if !ok || len(security) != 1 {
		return nil, errors.New("unsupported wireless security collection")
	}
	list, ok := security["pre_auth_acls"].([]any)
	if !ok || len(list) == 0 || len(list) > 1000 {
		return nil, errors.New("invalid pre-auth ACL collection")
	}
	out := []wirelessACL{}
	seen := map[string]bool{}
	for _, item := range list {
		m, ok := item.(map[string]any)
		if !ok {
			return nil, errInvalidResponse
		}
		// Map only pinned model fields; unknown input must not disappear.
		fields := map[string]string{"name": "aclListName", "acl_name": "aclName", "ipv6_enabled": "ipv6AclEnabled", "include_auto_generated_rules": "includeAutoGeneratedRules", "walled_garden_urls": "walledGardenUrls"}
		payload := map[string]any{"aclName": m["name"], "ipv6AclEnabled": false, "includeAutoGeneratedRules": true}
		for k, v := range m {
			if k == "rules" {
				continue
			}
			dest, ok := fields[k]
			if !ok || v == nil {
				return nil, errors.New("unsupported or null ACL field")
			}
			payload[dest] = v
		}
		rules, ok := m["rules"].([]any)
		if !ok {
			return nil, errors.New("ACL rules must be an explicit list")
		}
		translated := []any{}
		ruleFields := map[string]string{"source_address": "sourceAddress", "source_prefix": "sourceSubnetMaskOrPrefix", "destination_address": "destinationAddress", "destination_prefix": "destinationSubnetMaskOrPrefix", "source_ports": "sourcePorts", "destination_ports": "destinationPorts", "protocol": "protocol"}
		for _, item := range rules {
			r, ok := item.(map[string]any)
			if !ok {
				return nil, errInvalidResponse
			}
			rule := map[string]any{"sourceSubnetMaskOrPrefix": 32, "destinationSubnetMaskOrPrefix": 32, "sourcePorts": "0-65535", "destinationPorts": "0-65535"}
			for k, v := range r {
				dest, ok := ruleFields[k]
				if !ok || v == nil {
					return nil, errors.New("unsupported or null ACL rule field")
				}
				rule[dest] = v
			}
			translated = append(translated, rule)
		}
		payload["ipAclRules"] = translated
		encoded, _ := json.Marshal(payload)
		var desired wirelessACL
		if json.Unmarshal(encoded, &desired) != nil || validateWirelessACL(&desired) != nil || seen[desired.Name] {
			return nil, errors.New("invalid or repeated pre-auth ACL")
		}
		seen[desired.Name] = true
		out = append(out, desired)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}
func (c *client) wirelessACLs(ctx context.Context) (map[string]wirelessACL, error) {
	get := func(ctx context.Context, path string, q url.Values) ([]byte, error) { return c.get(ctx, path, q, 200) }
	rows, err := listInventoryQueryWithGet(ctx, get, wirelessACLsPath, nil, func(v json.RawMessage) string {
		var id struct {
			ID string `json:"id"`
		}
		_ = json.Unmarshal(v, &id)
		return id.ID
	})
	if err != nil {
		return nil, err
	}
	out := map[string]wirelessACL{}
	for _, raw := range rows {
		var presence map[string]json.RawMessage
		if json.Unmarshal(raw, &presence) != nil {
			return nil, errInvalidResponse
		}
		for _, k := range []string{"id", "aclListName", "aclName", "ipv6AclEnabled", "includeAutoGeneratedRules", "ipAclRules"} {
			if len(presence[k]) == 0 || string(presence[k]) == "null" {
				return nil, errInvalidResponse
			}
		}
		var ruleRows []map[string]json.RawMessage
		if json.Unmarshal(presence["ipAclRules"], &ruleRows) != nil {
			return nil, errInvalidResponse
		}
		for _, r := range ruleRows {
			for _, k := range []string{"sourceAddress", "sourceSubnetMaskOrPrefix", "destinationAddress", "destinationSubnetMaskOrPrefix", "protocol"} {
				if len(r[k]) == 0 || string(r[k]) == "null" {
					return nil, errInvalidResponse
				}
			}
		}
		var v wirelessACL
		if json.Unmarshal(raw, &v) != nil {
			return nil, errInvalidResponse
		}
		for i := range v.Rules {
			if v.Rules[i].SourcePorts == "" {
				v.Rules[i].SourcePorts = "0-65535"
			}
			if v.Rules[i].DestinationPorts == "" {
				v.Rules[i].DestinationPorts = "0-65535"
			}
		}
		if !validAPIID(v.ID) || validateWirelessACL(&v) != nil {
			return nil, errInvalidResponse
		}
		if _, ok := out[v.Name]; ok {
			return nil, errInvalidResponse
		}
		out[v.Name] = v
	}
	return out, nil
}
func wirelessACLMatches(want, got wirelessACL) bool {
	if want.Name != got.Name || want.ACLName != got.ACLName || want.IPv6 != got.IPv6 || want.AutoRules != got.AutoRules || !slices.Equal(want.Rules, got.Rules) {
		return false
	}
	return want.URLs == nil || reflect.DeepEqual(want.URLs, got.URLs) || (len(want.URLs) == 0 && len(got.URLs) == 0)
}

type wirelessACLExecutor struct {
	client  *client
	desired []wirelessACL
}

func (e *wirelessACLExecutor) count() int { return len(e.desired) }
func (e *wirelessACLExecutor) next(ctx context.Context) (*configurationWrite, error) {
	actual, err := e.client.wirelessACLs(ctx)
	if err != nil {
		return nil, err
	}
	for _, want := range e.desired {
		got, exists := actual[want.Name]
		if exists && wirelessACLMatches(want, got) {
			continue
		}
		method, path, action := http.MethodPost, wirelessACLsPath, "Create"
		identity := configurationResourceIdentity{}
		if exists {
			method, path, action = http.MethodPut, wirelessACLsPath+"/"+url.PathEscape(got.ID), "Update"
			identity.target = got.ID
			// PUT preserves optional URLs when the manifest does not own that field.
			if want.URLs == nil {
				want.URLs = got.URLs
			}
		}
		body, _ := json.Marshal(want)
		// Explicit [] must be sent to remove previously configured URL entries.
		if want.URLs != nil && len(want.URLs) == 0 {
			var m map[string]any
			_ = json.Unmarshal(body, &m)
			m["walledGardenUrls"] = []string{}
			body, _ = json.Marshal(m)
		}
		write := &configurationWrite{resource: "pre-auth-acl:" + want.Name, action: action, identity: identity, submit: func(ctx context.Context) (Task, error) {
			raw, err := e.client.mutate(ctx, method, path, body)
			if err != nil {
				return Task{}, err
			}
			var receipt struct {
				Response Task `json:"response"`
			}
			if json.Unmarshal(raw, &receipt) != nil || !validAPIID(receipt.Response.ID) {
				return Task{}, errInvalidResponse
			}
			return Task{ID: receipt.Response.ID}, nil
		}}
		if err := guardWirelessDefinitionWrite(write, actual, []string{want.Name}, e.client.wirelessACLs, func() any { return wirelessACLDispatchIntent(e.desired) }); err != nil {
			return nil, err
		}
		return write, nil
	}
	return nil, nil
}
func (e *wirelessACLExecutor) verify(ctx context.Context, op *ciskov1.NetworkControllerConfigurationOperation) (bool, error) {
	if op.ParentID != "" || op.TargetSerial != "" || (op.Action != "Create" && op.Action != "Update") || (op.Action == "Create" && op.TargetID != "") || (op.Action == "Update" && !validAPIID(op.TargetID)) {
		return false, errConfigurationTransition
	}
	actual, err := e.client.wirelessACLs(ctx)
	if err != nil {
		return false, err
	}
	for _, want := range e.desired {
		if op.Resource == "pre-auth-acl:"+want.Name {
			got, ok := actual[want.Name]
			return ok && wirelessACLMatches(want, got) && (op.TargetID == "" || op.TargetID == got.ID), nil
		}
	}
	return false, errConfigurationTransition
}
func (e *wirelessACLExecutor) report(ctx context.Context) ([]configapi.NetworkControllerDriftEntry, error) {
	actual, err := e.client.wirelessACLs(ctx)
	if err != nil {
		return nil, err
	}
	out := []configapi.NetworkControllerDriftEntry{}
	for _, want := range e.desired {
		got, ok := actual[want.Name]
		if ok && wirelessACLMatches(want, got) {
			continue
		}
		change := configapi.NetworkControllerDriftChangeAdd
		if ok {
			change = configapi.NetworkControllerDriftChangeUpdate
		}
		out = append(out, configapi.NetworkControllerDriftEntry{Section: "wireless", Resource: "pre-auth-acl:" + want.Name, Path: "/security_settings/pre_auth_acls", Change: change})
	}
	return out, nil
}
